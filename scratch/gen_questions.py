def has_long_vowel(ruby_text):
    # Check for Katakana long vowel
    if "ー" in ruby_text:
        return True
    # Check for common Hiragana long vowel patterns
    long_vowel_patterns = ["ああ", "いい", "うう", "ええ", "おお", "おう", "えい"]
    for p in long_vowel_patterns:
        if p in ruby_text:
            return True
    return False

def build_db(category):
    res = []
    seen_words = set()
    bgs = ["bg_beginner_1.png", "bg_beginner_2.png", "bg_beginner_3.png"]
    
    # Add existing
    for word, ruby_text in existing_db[category]:
        if word not in seen_words:
            if has_long_vowel(ruby_text):
                continue
            mora_list = to_mora_list(ruby_text)
            res.append({
                "word": word,
                "ruby": mora_list,
                "reverse": reverse_mora_list(mora_list),
                "bg": bgs[len(res) % len(bgs)]
            })
            seen_words.add(word)
    
    # Add new
    for word, ruby_text in new_words[category]:
        if word not in seen_words and len(res) < 100:
            if has_long_vowel(ruby_text):
                continue
            mora_list = to_mora_list(ruby_text)
            res.append({
                "word": word,
                "ruby": mora_list,
                "reverse": reverse_mora_list(mora_list),
                "bg": bgs[len(res) % len(bgs)]
            })
            seen_words.add(word)
            
    return res

